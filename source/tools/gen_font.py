#!/usr/bin/env python3
# gen_font.py — M10 desktop build-time font generator.
#
# Renders ASCII 32..126 from DejaVu Sans Mono (regular + bold) into 8x16
# bitmap cells and emits src/font8x16.h (included by src/fb.c and src/win.c).
# DejaVu fonts are freely redistributable (Bitstream Vera license).
#
# Deterministic: same font files -> same bytes, no timestamps.
#
# The generated table is COMMITTED at src/font8x16.h so that `make` needs
# neither Pillow nor the DejaVu fonts (same policy as src/microlm_weights.h).
# Regenerate deliberately, and commit the result:
#
#     python3 tools/gen_font.py            # -> src/font8x16.h
#     python3 tools/gen_font.py /tmp/x.h   # inspect without touching the tree
import os
import sys
from PIL import Image, ImageFont

CW, CH = 8, 16
FONTS = [
    ("AIOS_FONT8X16", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"),
    ("AIOS_FONT8X16B", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"),
]


def render_glyph(font, ch):
    """Render one char, crop to its bounding box, scale to fit 8x16 with a
    1px margin, threshold. Deterministic for a given font file."""
    hi = 4  # supersample factor
    img = Image.new("L", (CW * hi * 2, CH * hi * 2), 0)
    from PIL import ImageDraw
    d = ImageDraw.Draw(img)
    d.text((hi * 2, hi * 2), chr(ch), font=font, fill=255)
    bbox = img.getbbox()  # non-zero region
    if not bbox:
        return [0] * CH
    glyph = img.crop(bbox)
    # fit into (6 x 14) inside the 8x16 cell, keep aspect, centre
    gw, gh = glyph.size
    scale = min((CW - 2) / gw, (CH - 2) / gh)
    gw2, gh2 = max(1, int(gw * scale)), max(1, int(gh * scale))
    glyph = glyph.resize((gw2, gh2), Image.LANCZOS)
    cell = Image.new("L", (CW, CH), 0)
    cell.paste(glyph, ((CW - gw2) // 2, (CH - gh2) // 2))
    out = []
    for y in range(CH):
        row = 0
        for x in range(CW):
            if cell.getpixel((x, y)) >= 110:
                row |= 0x80 >> x
        out.append(row)
    return out


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "src/font8x16.h"
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    lines = [
        "/* font8x16.h — the 8x16 bitmap font used by aios-fb and the window core.",
        " * GENERATED by tools/gen_font.py from DejaVu Sans Mono (regular + bold),",
        " * ASCII 32..126, index by (codepoint - 32).",
        " *",
        " * COMMITTED ON PURPOSE, like src/microlm_weights.h: the generator needs",
        " * Pillow + DejaVu fonts, and the OS build must stay \"cc + make, nothing",
        " * else\". To regenerate after changing the font or the generator:",
        " *",
        " *     python3 tools/gen_font.py src/font8x16.h",
        " *",
        " * DejaVu fonts (c) Bitstream Vera / DejaVu contributors, free license.",
        " * The bitmap table is a build artifact of this repo, not a runtime",
        " * dependency: it compiles into the binary. */",
        "#ifndef AIOS_FONT8X16_H",
        "#define AIOS_FONT8X16_H",
        "",
        "#define AIOS_FONT_W 8",
        "#define AIOS_FONT_H 16",
        "#define AIOS_FONT_FIRST 32",
        "#define AIOS_FONT_LAST 126",
        "",
    ]
    for name, path in FONTS:
        if not os.path.exists(path):
            print(f"[gen_font] missing {path}", file=sys.stderr)
            sys.exit(1)
        # size chosen so the widest glyph (M/W) still fits 8 columns
        size = 28
        font = ImageFont.truetype(path, size)
        lines.append(f"static const unsigned char {name}[95][16] = {{")
        for ch in range(32, 127):
            rows = render_glyph(font, ch)
            cell = ", ".join(f"0x{r:02x}" for r in rows)
            c = chr(ch).replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    /* {c!r} */ {{ {cell} }},')
        lines.append("};")
        lines.append("")
        # glyph coverage check: all 95 printable ASCII glyphs must render
        blank = sum(
            1 for ch in range(33, 127)  # space (32) is legitimately blank
            if all(r == 0 for r in render_glyph(font, ch))
        )
        if blank:
            print(f"[gen_font] FAIL: {blank} blank glyphs in {name}",
                  file=sys.stderr)
            sys.exit(1)
    lines.append("#endif /* AIOS_FONT8X16_H */")
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    n = sum(1 for l in lines if l.startswith("static"))
    print(f"[gen_font] wrote {out_path} ({n} tables, 95 glyphs each)")


if __name__ == "__main__":
    main()
